// 맵 데이터 정리: 줄 길이를 맞추고 막힌 칸 표를 만든다
function prepareMap(id) {
  const m = MAPS[id];
  if (m.prepared) return m;
  m.id = id;
  m.h = m.rows.length;
  m.w = Math.max(...m.rows.map(r => r.length));
  m.rows = m.rows.map(r => r.padEnd(m.w, '#'));
  m.solid = [];
  for (let y = 0; y < m.h; y++) {
    m.solid.push([]);
    for (let x = 0; x < m.w; x++) m.solid[y].push(SOLID_TILES.has(m.rows[y][x]));
  }
  for (const hs of m.houses || []) {
    for (let y = hs.y; y < hs.y + hs.h; y++) for (let x = hs.x; x < hs.x + hs.w; x++) {
      if (y >= 0 && y < m.h && x >= 0 && x < m.w) m.solid[y][x] = true;
    }
  }
  if (m.boss) { m.solid[m.boss.y][m.boss.x] = false; }
  renderMapLayers(m);
  m.prepared = true;
  return m;
}
